(function () {
  const numberOrNull = value => {
    const source = String(value || "").trim();
    const parsed = Number(source);
    return source !== "" && Number.isFinite(parsed) ? parsed : null;
  };
  const normalizeType = value => {
    const type = String(value || "").trim().toLowerCase();
    if (type.includes("galaxy")) return "Galaxy";
    if (type.includes("globular")) return "Globular Cluster";
    if (type.includes("open cluster")) return "Open Cluster";
    if (type.includes("double")) return "Double star";
    return "Nebula";
  };
  const typeLabels = {
    "Galaxy": "Galaxia",
    "Globular Cluster": "Cúmulo Globular",
    "Open Cluster": "Cúmulo Abierto",
    "Nebula": "Nebulosa",
    "Double star": "Estrella Doble"
  };
  const metadata = window.MESSIER_METADATA;

  window.MESSIER_DATA_READY = d3.csv("../Proyecto/data/dataset.csv", row => {
    const id = String(row.Messier || "").trim();
    const extra = metadata[id] || {};
    const rawType = String(row.Object_Type || "").trim();
    const type = normalizeType(rawType);
    const sourceYear = String(row.Year || "").trim();
    const yearMatch = /^(\d{4})$/.exec(sourceYear);
    const dimensionsArea = numberOrNull(row.Dimensions) || 1;
    const radiusArcmin = Math.sqrt(dimensionsArea / Math.PI);
    return {
      id,
      number: numberOrNull(id.replace("M", "")),
      ngc: String(row.NGC || "").trim(),
      name: String(row.Name || "").trim(),
      nameEs: extra.nameEs || String(row.Name || "").trim() || ("Objeto " + id),
      type,
      subType: rawType,
      typeEs: typeLabels[type],
      constellation: String(row.Constellation || "").trim(),
      constellationEs: extra.constellationEs || String(row.Constellation || "").trim(),
      distance: numberOrNull(row.Distance),
      magnitude: numberOrNull(row.Magnitude),
      discoverer: String(row.Discoverer || "").trim(),
      year: yearMatch ? Number(yearMatch[1]) : 1610,
      yearOriginal: sourceYear || "No establecido",
      isAncient: Boolean(extra.isAncient),
      visibility: extra.visibility || "Consulta las condiciones de observación.",
      visLevel: extra.visLevel || "Variable",
      dimensionsArea,
      radiusArcmin,
      diameterArcmin: radiusArcmin * 2,
      moonRatio: (radiusArcmin * 2) / 31,
      image: "../Proyecto/img/" + id + ".png"
    };
  }).then(rows => {
    window.MESSIER_DATA = rows;
    return rows;
  }).catch(error => {
    console.error("No se pudo cargar el catálogo Messier compartido.", error);
    const message = document.getElementById("catalog-load-error");
    if (message) message.hidden = false;
    return [];
  });
})();